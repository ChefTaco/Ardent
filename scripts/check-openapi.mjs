import { readFile, writeFile, mkdir, mkdtemp, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { tmpdir } from 'node:os';
import { dirname, resolve } from 'node:path';
import SwaggerParser from '@apidevtools/swagger-parser';
import { ardentOpenApi } from '../dist/api.js';

const target = resolve(import.meta.dirname, '../openapi/ardent.json');
// Types of @hivemagnus/ardent-client (client/), which Ardent's own tests also use. They move with the API:
// --write regenerates them, and the check fails when they differ from the document.
const generatedTypes = resolve(import.meta.dirname, '../client/src/generated.ts');
const generator = resolve(import.meta.dirname, '../node_modules/.bin/openapi-typescript');
// The route manifest of @hivemagnus/ardent-client/openapi: every management-listener operation and whether it reads or acts.
const routeManifest = resolve(import.meta.dirname, '../client/src/routes.ts');
const exec = promisify(execFile);
// openapi-typescript 7 runs on the archived @redocly/openapi-core 1.x, which only calls
// minimatch (as minimatch 5's callable export) to match resolve.http.headers from a Redocly
// config. The repo pins minimatch 11 everywhere (GHSA-g3hv-75wg-m249), so there must be no
// Redocly config next to the generator.
for (const name of ['redocly.yaml', '.redocly.yaml', 'redocly.yml', '.redocly.yml']) {
  const path = resolve(import.meta.dirname, '..', name);
  if (existsSync(path)) throw new Error(`${path}: a Redocly config is not supported by the pinned openapi-typescript toolchain`);
}
const document = ardentOpenApi();
await SwaggerParser.validate(document);
const operations = new Set();
for (const [path, methods] of Object.entries(document.paths)) {
  for (const [method, operation] of Object.entries(methods)) {
    if (!['get', 'put', 'post', 'delete', 'patch'].includes(method)) continue;
    if (!operation.operationId || operations.has(operation.operationId)) throw new Error(`Missing or duplicate operationId at ${method.toUpperCase()} ${path}`);
    operations.add(operation.operationId);
    if (!operation.responses || !Object.keys(operation.responses).length) throw new Error(`Missing responses at ${method.toUpperCase()} ${path}`);
  }
}
const serialized = JSON.stringify(document, null, 2) + '\n';
/** One manifest entry per operation served by the management listener (A2A operations name their own server). */
function routes(doc) {
  const entries = [];
  for (const [path, methods] of Object.entries(doc.paths)) for (const [method, operation] of Object.entries(methods)) {
    if (!['get', 'put', 'post', 'delete', 'patch'].includes(method) || operation.servers) continue;
    const success = Object.entries(operation.responses).filter(([status]) => /^2/.test(status)).map(([, response]) => response);
    entries.push({ operationId: operation.operationId, method: method.toUpperCase(), path, kind: method === 'get' ? 'read' : 'action',
      auth: operation.security?.length ? 'bearer' : 'none', stream: success.some(response => Object.keys(response.content ?? {}).includes('text/event-stream')) });
  }
  return entries.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
}
const manifest = `// Generated by scripts/check-openapi.mjs from openapi/ardent.json (npm run openapi:write). Do not edit.
/** Every operation of the management API: \`read\` for GET, \`action\` otherwise; \`stream\` when it answers with server-sent events. */
export const ARDENT_ROUTES = ${JSON.stringify(routes(document), null, 2).replace(/"([A-Za-z]+)":/g, '$1:').replace(/"/g, "'")} as const;
`;
if (process.argv.includes('--write')) {
  await mkdir(dirname(target), { recursive: true });
  await writeFile(target, serialized);
  await exec(generator, [target, '-o', generatedTypes], { timeout: 30_000 });
  await writeFile(routeManifest, manifest);
  process.stdout.write(`Wrote ${target} (${operations.size} operations)\n`);
} else {
  const committed = await readFile(target, 'utf8');
  if (committed !== serialized) throw new Error(`Ardent OpenAPI drift: run npm run openapi:write and review ${target}`);
  const dir = await mkdtemp(resolve(tmpdir(), 'ardent-openapi-'));
  try {
    const expectedTypes = resolve(dir, 'ardent-openapi.ts');
    await exec(generator, [target, '-o', expectedTypes], { timeout: 30_000 });
    const committedTypes = await readFile(generatedTypes, 'utf8').catch(() => '');
    if (committedTypes !== await readFile(expectedTypes, 'utf8'))
      throw new Error(`Ardent client types drift: run npm run openapi:write and review ${generatedTypes}`);
    if (await readFile(routeManifest, 'utf8').catch(() => '') !== manifest)
      throw new Error(`Ardent client route manifest drift: run npm run openapi:write and review ${routeManifest}`);
  } finally { await rm(dir, { recursive: true, force: true }); }
  process.stdout.write(`Ardent OpenAPI 3.1 validated (${operations.size} operations)\n`);
}
